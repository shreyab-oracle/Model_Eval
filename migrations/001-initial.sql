CREATE TABLE AIE_DOCUMENTS (
 id VARCHAR2(64) PRIMARY KEY, kind VARCHAR2(30) NOT NULL, parent_id VARCHAR2(64),
 version_name VARCHAR2(120), digest VARCHAR2(64) NOT NULL, payload CLOB NOT NULL CHECK (payload IS JSON),
 created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
)
-- @statement
CREATE INDEX AIE_DOC_KIND_PARENT ON AIE_DOCUMENTS(kind, parent_id)
-- @statement
CREATE TABLE AIE_RUNS (
 id VARCHAR2(64) PRIMARY KEY, manifest_id VARCHAR2(64) NOT NULL REFERENCES AIE_DOCUMENTS(id),
 status VARCHAR2(20) NOT NULL, run_kind VARCHAR2(20) NOT NULL, live NUMBER(1) DEFAULT 1 NOT NULL,
 report_id VARCHAR2(64), error CLOB, created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
)
-- @statement
CREATE TABLE AIE_TASKS (
 id VARCHAR2(64) PRIMARY KEY, run_id VARCHAR2(64) NOT NULL REFERENCES AIE_RUNS(id),
 stage VARCHAR2(20) NOT NULL, case_id VARCHAR2(120), model_role VARCHAR2(20), repetition NUMBER(2), assessment NUMBER(1),
 depends_on VARCHAR2(64) REFERENCES AIE_TASKS(id), payload CLOB NOT NULL CHECK(payload IS JSON),
 status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL, owner VARCHAR2(64), lease_until TIMESTAMP WITH TIME ZONE,
 attempts NUMBER(5) DEFAULT 0 NOT NULL, retry_cycle NUMBER(5) DEFAULT 0 NOT NULL,
 due_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, error CLOB,
 created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
)
-- @statement
CREATE INDEX AIE_TASK_CLAIM ON AIE_TASKS(status,due_at,run_id)
-- @statement
CREATE TABLE AIE_ATTEMPTS (
 id VARCHAR2(64) PRIMARY KEY, task_id VARCHAR2(64) NOT NULL REFERENCES AIE_TASKS(id), owner VARCHAR2(64) NOT NULL,
 retry_cycle NUMBER(5) NOT NULL, attempt_number NUMBER(5) NOT NULL, status VARCHAR2(20) NOT NULL,
 result CLOB, started_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, finished_at TIMESTAMP WITH TIME ZONE
)
